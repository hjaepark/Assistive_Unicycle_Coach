#!/bin/bash
#SBATCH -J v2_lambda_sweep
#SBATCH --account=gts-skousik3-paid
#SBATCH --array=0-6
#SBATCH -N 1
#SBATCH -n 16
#SBATCH --mem=64G
#SBATCH -t 48:00:00
#SBATCH -q inferno
#SBATCH -o sweep_logs/v2_lambda_%A_%a.out
#SBATCH -e sweep_logs/v2_lambda_%A_%a.err
#SBATCH --mail-type=BEGIN,END,FAIL
#SBATCH --mail-user=hpark459@gatech.edu

cd $SLURM_SUBMIT_DIR
mkdir -p sweep_logs

source ~/.bashrc
conda activate unienv

# Lambda values to sweep
LAMBDAS=(1 5 10 25 50 100 200)
LAMBDA=${LAMBDAS[$SLURM_ARRAY_TASK_ID]}

echo "================================"
echo "V2 Lambda Sweep"
echo "Array Job ID: $SLURM_ARRAY_JOB_ID"
echo "Worker ID: $SLURM_ARRAY_TASK_ID / 6"
echo "Lambda: $LAMBDA"
echo "Node: $SLURM_NODELIST"
echo "Started: $(date)"
echo "================================"

# Generate config yaml for this lambda value
CONFIG_DIR="train/unicycle_train/coach/v2/configs"
CONFIG_FILE="${CONFIG_DIR}/gs1000_lambda${LAMBDA}.yaml"

mkdir -p $CONFIG_DIR

cat > $CONFIG_FILE << EOF
# Auto-generated by sweep_lambda.sh
# Lambda action penalty = ${LAMBDA}
training:
  coach_gradient_steps: 1000

reward:
  lambda_action: ${LAMBDA}
EOF

echo "Config: $CONFIG_FILE"
cat $CONFIG_FILE
echo "================================"

# Run V2 training
python -m train.unicycle_train.coach.v2.train \
    --config $CONFIG_FILE \
    --max_students 50

echo "================================"
echo "Lambda $LAMBDA DONE at $(date)"
echo "================================"